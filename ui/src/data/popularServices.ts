/**
 * Lazy-load cache for studio covers to eliminate heavy base64 strings from main bundle.
 */
let coversCache: Record<string, string> | null = null;

export async function loadServiceCovers(): Promise<Record<string, string>> {
  if (!coversCache) {
    const mod = await import("./serviceCovers");
    coversCache = mod.SERVICE_COVERS;
  }
  return coversCache;
}

export async function getServiceCoverAsync(presetId: string): Promise<string> {
  const covers = await loadServiceCovers();
  return covers[presetId] || "";
}

export function getServiceCover(presetId: string): string | null {
  return coversCache ? (coversCache[presetId] || null) : null;
}

export function generateBrandVectorSvg(preset: PopularServicePreset): string {
  const bg = preset.brandColor || "#18181b";
  const name = preset.name;
  const arName = preset.arabicName || "";
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 360" width="640" height="360">
    <defs>
      <linearGradient id="g_${preset.id}" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bg}" stop-opacity="0.95"/>
        <stop offset="100%" stop-color="#09090b" stop-opacity="0.98"/>
      </linearGradient>
    </defs>
    <rect width="640" height="360" fill="url(#g_${preset.id})"/>
    <circle cx="320" cy="150" r="60" fill="#ffffff" fill-opacity="0.12"/>
    <text x="320" y="160" font-family="system-ui, -apple-system, sans-serif" font-size="32" font-weight="bold" fill="#ffffff" text-anchor="middle">${name}</text>
    <text x="320" y="210" font-family="system-ui, -apple-system, sans-serif" font-size="20" fill="#ffffff" fill-opacity="0.75" text-anchor="middle">${arName}</text>
  </svg>`;
  return "data:image/svg+xml;utf8," + encodeURIComponent(svg);
}

export function generateCinematicCoverSvg(preset: PopularServicePreset): string {
  if (coversCache && coversCache[preset.id]) {
    return coversCache[preset.id];
  }
  return generateBrandVectorSvg(preset);
}
